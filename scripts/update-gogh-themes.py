#!/usr/bin/env python3
"""Regenerates Sources/Satellite/GoghThemes.swift from Gogh's themes (https://github.com/Gogh-Co/Gogh, MIT).

The themes are vendored, not downloaded by the app: Satellite works offline and ships exactly the colors in this
repository. To update, pass the Gogh commit to read (a full 40-character id, so the result is reproducible), review
the diff, and update the commit in THIRD_PARTY_NOTICES.md:

    scripts/update-gogh-themes.py 3277da1a295142cd8664e0657c5a3c2a44cc520a

Every theme must have 16 ANSI colors, a background, a foreground and a cursor, all #RRGGBB; anything else is skipped
and reported. Authors and hashes are dropped to keep the file small.
"""
import json
import pathlib
import re
import sys
import urllib.request

OUT = pathlib.Path(__file__).resolve().parent.parent / "Sources/Satellite/GoghThemes.swift"
HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")
ANSI = [f"color_{i:02d}" for i in range(1, 17)]


def main():
    if len(sys.argv) != 2 or not re.fullmatch(r"[0-9a-f]{40}", sys.argv[1]):
        sys.exit("usage: update-gogh-themes.py <full 40-character Gogh commit>")
    commit = sys.argv[1]
    url = f"https://raw.githubusercontent.com/Gogh-Co/Gogh/{commit}/data/themes.json"
    with urllib.request.urlopen(url, timeout=60) as response:
        themes = json.load(response)

    lines, skipped, names = [], [], set()
    for theme in themes:
        name = str(theme.get("name", "")).strip()
        colors = [theme.get(key) for key in ["background", "foreground", "cursor"] + ANSI]
        problem = None
        if not name or any(c in name for c in "|\n\r\"\\") or "\"#" in name:
            problem = "unusable name"
        elif name in names:
            problem = "duplicate name"
        elif theme.get("variant") not in ("dark", "light"):
            problem = f"variant {theme.get('variant')!r}"
        elif not all(isinstance(c, str) and HEX.match(c) for c in colors):
            problem = "missing or malformed colors"
        if problem:
            skipped.append(f"{name or '?'}: {problem}")
            continue
        names.add(name)
        variant = "d" if theme["variant"] == "dark" else "l"
        lines.append("|".join([name, variant] + [c[1:].upper() for c in colors]))

    lines.sort(key=lambda line: (line.split("|", 1)[0].casefold(), line))   # by name: "Dracula" before "Dracula Lost"
    OUT.write_text(
        "// Generated by scripts/update-gogh-themes.py from Gogh (https://github.com/Gogh-Co/Gogh), MIT licensed; see\n"
        "// THIRD_PARTY_NOTICES.md. Don't edit by hand: run the script with a Gogh commit to update.\n"
        "//\n"
        "// One theme per line: name | d (dark) or l (light) | background | foreground | cursor | the 16 ANSI colors.\n"
        "enum GoghThemes {\n"
        f"    static let commit = \"{commit}\"\n"
        f"    static let count = {len(lines)}\n"
        "    static let data = #\"\"\"\n"
        + "\n".join(lines) + "\n"
        "\"\"\"#\n"
        "}\n")
    print(f"{len(lines)} themes from Gogh {commit[:12]} -> {OUT.relative_to(OUT.parent.parent.parent)}")
    for line in skipped:
        print("skipped:", line)


if __name__ == "__main__":
    main()
